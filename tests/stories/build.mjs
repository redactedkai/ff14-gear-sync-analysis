#!/usr/bin/env node
/* Builds the story gallery (npm run test:stories runs it first): lists the story files (esbuild has no glob import),
   writes tests/stories/out/registry.generated.js, and bundles tests/stories/gallery/main.js into one IIFE
   (tests/stories/out/gallery.js and .css, next to index.html) that opens from file://. Lit's development build is used, so
   its errors and warnings (the class-field trap, a change in update) reach the console. */
import * as esbuild from 'esbuild';
import { mkdirSync, readFileSync, readdirSync, statSync, writeFileSync } from 'node:fs';
import { dirname, join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';
import { BROWSER_TARGETS } from '../../scripts/build/build.mjs';

// the folder of the stories gallery (tests/stories/)
const STORIES_DIR = dirname(fileURLToPath(import.meta.url));
// where the gallery is built (gitignored)
const OUT_DIR = join(STORIES_DIR, 'out');

/* Every file under `folder`, as paths with forward slashes (the `out` folder is skipped). */
function listFiles(folder) {
  return readdirSync(folder).flatMap(name => {
    const path = join(folder, name);
    if (statSync(path).isDirectory()) {
      return name === 'out' ? [] : listFiles(path);
    }
    return [path.replaceAll('\\', '/')];
  });
}

/* Writes the registry: one lazy import per `*.story.{js,ts}` file, keyed by its path under tests/stories without the
   extension ('app/gsa-counter'). Returns the number of story files. */
function writeRegistry() {
  const storyFiles = listFiles(STORIES_DIR).filter(file => /\.story\.(js|ts)$/.test(file));
  const lines = storyFiles.map(file => {
    const id = relative(STORIES_DIR, file)
      .replaceAll('\\', '/')
      .replace(/\.story\.\w+$/, '');
    return `  ${JSON.stringify(id)}: () => import(${JSON.stringify(file)}),`;
  });
  mkdirSync(OUT_DIR, { recursive: true });
  const text = `// Generated by tests/stories/build.mjs; never edited by hand.\nexport const stories = {\n${lines.join('\n')}\n};\n`;
  writeFileSync(join(OUT_DIR, 'registry.generated.js'), text);
  return storyFiles.length;
}

/* Builds the gallery into out/ and returns the number of story files. */
async function buildGallery() {
  const storyCount = writeRegistry();
  await esbuild.build({
    entryPoints: [join(STORIES_DIR, 'gallery/main.js')],
    outdir: OUT_DIR,
    entryNames: 'gallery',
    bundle: true,
    format: 'iife',
    target: BROWSER_TARGETS,
    // Lit's development build (its dev-mode errors and warnings)
    conditions: ['development'],
    sourcemap: 'inline',
    tsconfig: join(STORIES_DIR, '../../tsconfig.json'),
    logLevel: 'warning',
  });
  // the stylesheet goes inline: from file:// axe-core cannot read a linked one (a cross-origin error in every engine)
  const css = readFileSync(join(OUT_DIR, 'gallery.css'), 'utf-8');
  const page = readFileSync(join(STORIES_DIR, 'gallery/index.html'), 'utf-8');
  writeFileSync(
    join(OUT_DIR, 'index.html'),
    page.replace(
      '<!-- STYLES -->',
      () => `<style>
${css}</style>`,
    ),
  );
  return storyCount;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const started = performance.now();
  const storyCount = await buildGallery();
  console.log(`stories: gallery built from ${storyCount} story files in ${Math.round(performance.now() - started)} ms`);
}
